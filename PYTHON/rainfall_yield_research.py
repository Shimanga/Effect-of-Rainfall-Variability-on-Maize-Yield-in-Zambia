def re_cluster_robust(df, y_col, x_cols, entity_col='province', time_col='year'):
    """GLS random effects with cluster-robust sandwich SE."""
    df = df.copy().reset_index(drop=True)
    entities = df[entity_col].values; unique_ents = np.unique(entities)
    N = len(unique_ents); n = len(df); k = len(x_cols)
    for col in [y_col]+x_cols:
        df[col+'_dm'] = df[col] - df.groupby(entity_col)[col].transform('mean')
    y_dm = df[y_col+'_dm'].values
    X_dm = np.column_stack([df[c+'_dm'].values for c in x_cols])
    b_fe = np.linalg.lstsq(X_dm, y_dm, rcond=None)[0]
    r_fe = y_dm - X_dm@b_fe
    # Variance components (Swamy-Arora)
    df_w = max(n - N - k, 1); sigma2_e = np.sum(r_fe**2)/df_w
    T_i  = df.groupby(entity_col).size().values; T_bar = n/N
    mn   = df.groupby(entity_col)[[y_col]+x_cols].mean().reset_index()
    y_be = mn[y_col].values; X_be = mn[x_cols].values
    X_be_i = np.column_stack([np.ones(N), X_be])
    b_be = np.linalg.lstsq(X_be_i, y_be, rcond=None)[0]
    r_be = y_be - X_be_i@b_be
    sigma2_u = max(np.sum(r_be**2)/max(N-k-1,1) - sigma2_e/T_bar, 0)
    # GLS quasi-demeaning weights
    theta = 1 - np.sqrt(sigma2_e/(T_i*sigma2_u + sigma2_e + 1e-12))
    theta_map = dict(zip(unique_ents, theta))
    tv  = np.array([theta_map[e] for e in entities])
    emy = df.groupby(entity_col)[y_col].transform('mean').values
    emx = {c: df.groupby(entity_col)[c].transform('mean').values for c in x_cols}
    y_gls = df[y_col].values - tv*emy
    X_gls = np.column_stack([np.ones(n)] + [df[c].values - tv*emx[c] for c in x_cols])
    b_re  = np.linalg.lstsq(X_gls, y_gls, rcond=None)[0]
    r_re  = y_gls - X_gls@b_re
    # Cluster-robust sandwich SE
    kf = X_gls.shape[1]; XtXi = np.linalg.inv(X_gls.T@X_gls)
    meat = np.zeros((kf, kf))
    for ent in unique_ents:
        mk = entities==ent; sg = X_gls[mk].T@r_re[mk]; meat += np.outer(sg,sg)
    corr = (N/(N-1))*((n-1)/(n-kf))
    V_re_cl = corr * XtXi @ meat @ XtXi
    return b_re[1:], V_re_cl[1:, 1:]  # drop intercept

