def f_test_all_x(m):
    """Wald F-test for joint significance of all substantive regressors."""
    nx = m['n_x']; bx = m['beta_full'][:nx]; Vx = m['V_full'][:nx, :nx]
    W  = bx @ np.linalg.pinv(Vx) @ bx / nx
    p  = 1 - scipy_stats.f.cdf(W, dfn=nx, dfd=m['df_resid'])
    return W, p, nx

