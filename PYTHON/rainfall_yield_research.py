# ── 3. WOOLDRIDGE TEST FOR SERIAL CORRELATION ─────────────────────────────
def wooldridge_serial(df, y_col, x_cols, entity_col='province', time_col='year'):
    """
    Wooldridge (2002) test for first-order serial correlation in FE residuals.
    First-differences the FE residuals; regresses FD residuals on their lag.
    H0: no serial correlation → slope coefficient = -0.5.
    """
    df = df.copy().sort_values([entity_col, time_col]).reset_index(drop=True)
    for col in [y_col] + x_cols:
        df[col+'_dm'] = df[col] - df.groupby(entity_col)[col].transform('mean')
    y_dm = df[y_col+'_dm'].values
    X_dm = np.column_stack([df[c+'_dm'].values for c in x_cols])
    b    = np.linalg.lstsq(X_dm, y_dm, rcond=None)[0]
    df['rfe']     = y_dm - X_dm @ b
    df['rfd']     = df.groupby(entity_col)['rfe'].diff()
    df['rfd_lag'] = df.groupby(entity_col)['rfd'].shift(1)
    sub = df.dropna(subset=['rfd', 'rfd_lag'])
    y_w = sub['rfd'].values; X_w = sub['rfd_lag'].values
    b_w = np.dot(X_w, y_w) / np.dot(X_w, X_w)
    r_w = y_w - X_w * b_w; nw = len(y_w)
    s2  = np.sum(r_w**2) / (nw - 1)
    se_b = np.sqrt(s2 / np.dot(X_w, X_w))
    t    = (b_w - (-0.5)) / se_b
    p    = 2 * (1 - scipy_stats.t.cdf(np.abs(t), df=nw - 1))
    return t, p, b_w

