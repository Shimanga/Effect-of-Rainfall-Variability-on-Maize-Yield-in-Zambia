def hausman_test(df, y_col, x_cols, entity_col='province', time_col='year'):
    df=df.copy().reset_index(drop=True)
    for col in [y_col]+x_cols:
        df[col+'_dm']=df[col]-df.groupby(entity_col)[col].transform('mean')
    y_dm=df[y_col+'_dm'].values
    X_dm=np.column_stack([df[c+'_dm'].values for c in x_cols])
    b_fe=np.linalg.lstsq(X_dm,y_dm,rcond=None)[0]
    r_fe=y_dm-X_dm@b_fe; n=len(y_dm); k=len(x_cols)
    s2_fe=np.sum(r_fe**2)/(n-k-df[entity_col].nunique())
    V_fe=s2_fe*np.linalg.inv(X_dm.T@X_dm)
    mn=df.groupby(entity_col)[[y_col]+x_cols].mean().reset_index()
    y_be=mn[y_col].values; X_be=mn[x_cols].values
    b_re=np.linalg.lstsq(X_be,y_be,rcond=None)[0]
    r_re=y_be-X_be@b_re
    s2_re=np.sum(r_re**2)/max(len(mn)-k,1)
    V_re=s2_re*np.linalg.inv(X_be.T@X_be)
    diff=b_fe-b_re; V_diff=V_fe-V_re
    ev=np.linalg.eigvalsh(V_diff)
    if np.all(ev>=-1e-10): H=diff@np.linalg.pinv(V_diff)@diff
    else: H=np.sum(diff**2/np.maximum(np.diag(V_fe)-np.diag(V_re),1e-12))
    p=1-scipy_stats.chi2.cdf(H,df=k)
    return H,p,k

