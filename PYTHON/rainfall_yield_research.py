# ── 2. F-TEST: JOINT SIGNIFICANCE OF YEAR DUMMIES ────────────────────────
def f_test_time_dummies(m):
    """Wald F-test for joint significance of year fixed effects."""
    nx = m['n_x']
    bt = m['beta_full'][nx:]          # time-dummy coefficients
    kt = len(bt)
    Vt = m['V_full'][nx:, nx:]        # DK variance submatrix for time dummies
    W  = (bt @ np.linalg.pinv(Vt) @ bt) / kt
    p  = 1 - scipy_stats.f.cdf(W, dfn=kt, dfd=m['df_resid'])
    return W, p, kt

