# ── TWO-WAY FE WITH DRISCOLL-KRAAY STANDARD ERRORS ───────────────────────
def fe_2way_dk(df, y_col, x_cols, entity_col='province', time_col='year', L=None):
    """
    Two-way FE (entity + time) with Driscoll-Kraay standard errors.

    Entity FE: within-demeaning (province means subtracted).
    Time FE:   year dummies added to demeaned regression.
    SE method: Driscoll & Kraay (1998) — robust to heteroskedasticity,
               autocorrelation up to L lags, and cross-sectional dependence.
               Bandwidth L defaults to floor(T^(1/4)) per Hoechle (2007).
    Inference: t-distribution with df = T - L - 1.
    """
    df = df.copy().reset_index(drop=True)

    # Step 1: within-demean all variables by entity
    for col in [y_col] + x_cols:
        df[col+'_dm'] = df[col] - df.groupby(entity_col)[col].transform('mean')

    # Step 2: design matrix — demeaned Xs + year dummies
    time_dummies = pd.get_dummies(df[time_col], prefix='yr', drop_first=True).astype(float)
    y  = df[y_col+'_dm'].values
    X  = np.column_stack([df[c+'_dm'].values for c in x_cols] + [time_dummies.values])
    k  = X.shape[1]; n = len(y)

    # Step 3: OLS coefficients
    XtXi = np.linalg.inv(X.T @ X)
    beta  = XtXi @ (X.T @ y)
    resid = y - X @ beta
    fitted = X @ beta

    # Step 4: Driscoll-Kraay SE
    time_index = df[time_col].values
    T_vals = np.unique(time_index); T = len(T_vals)
    if L is None:
        L = int(np.floor(T ** (1/4)))   # default bandwidth = floor(T^0.25)
    t_map  = {t: i for i, t in enumerate(T_vals)}
    t_idx  = np.array([t_map[t] for t in time_index])

    # Cross-sectional score sums per time period: h_t = sum_i X_it * e_it
    H = np.zeros((T, k))
    for t in range(T):
        mask = t_idx == t
        H[t] = X[mask].T @ resid[mask]

    # Newey-West kernel on H (Bartlett weights)
    S = H.T @ H                               # lag-0 term
    for l in range(1, L + 1):
        w  = 1 - l / (L + 1)                 # Bartlett weight
        Gl = H[l:].T @ H[:-l]
        S += w * (Gl + Gl.T)

    # Small-sample correction factor
    correction = (n / (n - k)) * (T / (T - 1))
    V_dk = correction * XtXi @ S @ XtXi
    se   = np.sqrt(np.diag(V_dk))
    df_t = T - L - 1                          # DK degrees of freedom
    t_stat = beta / se
    p_val  = 2 * (1 - scipy_stats.t.cdf(np.abs(t_stat), df=df_t))

    # Step 5: R-squared (within and overall)
    r2_within = 1 - np.sum(resid**2) / np.sum((y - y.mean())**2)
    emy = df.groupby(entity_col)[y_col].transform('mean').values
    fo  = fitted + emy
    r2_overall = 1 - (np.sum((df[y_col].values - fo)**2) /
                      np.sum((df[y_col].values - df[y_col].mean())**2))

    n_x = len(x_cols)
    return dict(
        x_labels=x_cols,
        beta=beta[:n_x], se=se[:n_x], t=t_stat[:n_x], p=p_val[:n_x],
        r2_within=r2_within, r2_overall=r2_overall,
        resid=resid, fitted=fitted, obs=n,
        groups=len(np.unique(df[entity_col])),
        T_unique=T, L=L, df_resid=df_t,
        V_full=V_dk, beta_full=beta, se_full=se,
        t_full=t_stat, p_full=p_val,
        X=X, y=y, XtXi=XtXi, n_x=n_x,
    )

