def compute_vif(X_df):
    """VIF_j = 1/(1-R²_j), R²_j from regressing x_j on all other x's."""
    cols = X_df.columns.tolist(); vifs = {}
    for col in cols:
        y_v = X_df[col].values
        others = [c for c in cols if c != col]
        Xo = np.column_stack([np.ones(len(y_v))] + [X_df[c].values for c in others])
        b  = np.linalg.lstsq(Xo, y_v, rcond=None)[0]
        yh = Xo @ b
        ss_r = np.sum((y_v - yh)**2); ss_t = np.sum((y_v - y_v.mean())**2)
        r2 = 1 - ss_r/ss_t if ss_t > 0 else 0
        vifs[col] = round(1/(1-r2) if r2 < 1 else np.inf, 3)
    return vifs

