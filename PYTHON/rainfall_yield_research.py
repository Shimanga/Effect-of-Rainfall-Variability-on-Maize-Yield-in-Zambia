from scipy.stats import gamma, norm

# --- Helper: fit gamma and return SPI values ---
def fit_spi(values):
    """Fit gamma distribution and convert CDF to standard normal (SPI)."""
    shape, loc, scale = gamma.fit(values, floc=0)  # fix loc=0 (standard for SPI)
    cdf_vals = gamma.cdf(values, shape, loc=loc, scale=scale)
    cdf_vals = np.clip(cdf_vals, 1e-6, 1 - 1e-6)  # avoid -inf/+inf at tails
    return norm.ppf(cdf_vals)

# --- Helper: classify SPI into drought categories ---
def classify_drought(spi):
    if spi > 0:
        return 'Wet'
    elif spi >= -0.99:
        return 'Mild Dry'
    elif spi >= -1.49:
        return 'Moderate Drought'
    elif spi >= -1.99:
        return 'Severe Drought'
    else:
        return 'Extreme Drought'

# --- Compute SPI for each province ---
spi_results = []

for province in sorted(df_monthly['province'].unique()):
    pdata = df_monthly[df_monthly['province'] == province].copy()

    # SPI-3: sum Oct + Nov + Dec for each season year
    ond = (
        pdata[pdata['month'].isin([10, 11, 12])]
        .groupby('season')['rfh']
        .sum()
        .reset_index()
        .rename(columns={'rfh': 'OND_sum'})
    )
    ond['SPI_3_OND'] = fit_spi(ond['OND_sum'].values)

    # SPI-6: sum all 6 months of season (Oct–Mar, already labeled by season)
    ondjfm = (
        pdata.groupby('season')['rfh']
        .sum()
        .reset_index()
        .rename(columns={'rfh': 'ONDJFM_sum'})
    )
    ondjfm['SPI_6_ONDJFM'] = fit_spi(ondjfm['ONDJFM_sum'].values)

    # Merge SPI-3 and SPI-6
    merged = ond.merge(ondjfm, on='season')
    merged['province'] = province
    merged['drought_class_3'] = merged['SPI_3_OND'].apply(classify_drought)
    merged['drought_class_6'] = merged['SPI_6_ONDJFM'].apply(classify_drought)
    spi_results.append(merged)

# --- Assemble final DataFrame ---
