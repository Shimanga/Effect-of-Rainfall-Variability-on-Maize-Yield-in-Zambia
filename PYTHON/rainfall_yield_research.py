# ── 4. PESARAN CD TEST FOR CROSS-SECTIONAL DEPENDENCE ────────────────────
def pesaran_cd_test(df, resid_col, entity_col='province', time_col='year'):
    """
    Pesaran (2004) CD test for cross-sectional dependence.
    CD = sqrt(2T / (N(N-1))) * sum_{i<j} rho_ij  ~  N(0,1) under H0.
    Uses pairwise correlations of residuals across provinces over time.
    """
    piv = df.pivot(index=time_col, columns=entity_col, values=resid_col)
    provinces = piv.columns.tolist(); N = len(provinces); T = piv.shape[0]
    rho_sum = 0.0; pairs = 0
    for i in range(N):
        for j in range(i + 1, N):
            xi = piv.iloc[:, i]; xj = piv.iloc[:, j]
            mask = xi.notna() & xj.notna()
            if mask.sum() < 3: continue
            r, _ = scipy_stats.pearsonr(xi[mask], xj[mask])
            rho_sum += r; pairs += 1
    CD    = np.sqrt(2 * T / (N * (N - 1))) * rho_sum
    p_val = 2 * (1 - scipy_stats.norm.cdf(np.abs(CD)))
    avg_rho = rho_sum / max(pairs, 1)
    return CD, p_val, avg_rho, pairs

